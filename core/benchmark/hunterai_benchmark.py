@dataclass
class StageResult:
    stage_number: int
    stage_name: str
    max_score: float
    awarded_score: float
    passed: bool
    details: List[str] = field(default_factory=list)


@dataclass
class BenchmarkReport:
    total_score: float
    max_possible: float = 100.0
    grade: str = "Unspecified"
    verdict: str = "Unspecified"
    stages: List[StageResult] = field(default_factory=list)
    elapsed_seconds: float = 0.0

    def to_markdown(self) -> str:
        lines = [
            "# [REPORT] HunterAI Agentic Benchmark Evaluation Report",
            "",
            f"**Total Benchmark Score:** `{self.total_score:.1f} / {self.max_possible:.1f}` (**{self.grade}**)",
            f"**Verdict:** {self.verdict}",
            f"**Evaluation Duration:** {self.elapsed_seconds:.2f}s",
            "",
            "---",
            "",
            "## Detailed Stage-by-Stage Scorecard",
            "",
            "| # | Evaluation Dimension | Score | Status | Key Observations |",
            "|---|---|---|---|---|",
        ]

        for st in self.stages:
            status_icon = "[+] PASSED" if st.passed else "[-] FAILED"
            details_str = "; ".join(st.details[:2])
            lines.append(
                f"| Stage {st.stage_number} | **{st.stage_name}** | {st.awarded_score:.1f}/{st.max_score:.1f} | {status_icon} | {details_str} |"
            )

        lines.extend([
            "",
            "---",
            "",
            "### Benchmark Rating Scale:",
            "- `90-100` [A+] Autonomous Cognitive Security Agent (Top Tier)",
            "- `75-89`  [A]  Advanced Agent with Resilient Capabilities",
            "- `60-74`  [B]  Standard Functional Agent",
            "- `40-59`  [C]  Advanced Tool Runner / Script Orchestrator",
            "- `0-39`   [D]  Basic LLM Command Dispatcher",
            "",
            "---",
            f"*Generated by HunterAI Autonomous Benchmark Suite at {time.strftime('%Y-%m-%d %H:%M:%S')}*"
        ])
        return "\n".join(lines)


class HunterAIBenchmarkRunner:
    """
    مشغل تقييم واختبار النضج الذاتي لـ HunterAI عبر المراحل الـ 12
    """

    def __init__(self, workspace_root: Path):
        self.workspace_root = workspace_root
        self.workspace_root.mkdir(parents=True, exist_ok=True)

    async def run_full_benchmark(self) -> BenchmarkReport:
        t0 = time.time()
        stages: List[StageResult] = []

        # ── Stage 0: Basics & Workspace ──────────────────────────────
        st0 = self._eval_stage_0()
        stages.append(st0)

        # ── Stage 1: Tool Discovery & Planning ───────────────────────
        st1 = self._eval_stage_1()
        stages.append(st1)

        # ── Stage 2: File Intelligence ───────────────────────────────
        st2 = self._eval_stage_2()
        stages.append(st2)

        # ── Stage 3: Dependency & Degradation Resilience ─────────────
        st3 = self._eval_stage_3()
        stages.append(st3)

        # ── Stage 4: Playwright & Browser Intelligence ───────────────
        st4 = await self._eval_stage_4()
        stages.append(st4)

        # ── Stage 5: Dynamic State Observation ───────────────────────
        st5 = self._eval_stage_5()
        stages.append(st5)

        # ── Stage 6: UI <-> Network Traffic Correlation ──────────────
        st6 = self._eval_stage_6()
        stages.append(st6)

        # ── Stage 7: Scientific Security Reasoning ───────────────────
        st7 = self._eval_stage_7()
        stages.append(st7)

        # ── Stage 8: False Positive Filtering & Gating ───────────────
        st8 = self._eval_stage_8()
        stages.append(st8)

        # ── Stage 9: Memory Persistence & Resume ─────────────────────
        st9 = self._eval_stage_9()
        stages.append(st9)

        # ── Stage 10: Tool Failure Recovery & Fallbacks ──────────────
        st10 = self._eval_stage_10()
        stages.append(st10)

        # ── Stage 11: Scope Guard & Sandboxing ───────────────────────
        st11 = self._eval_stage_11()
        stages.append(st11)

        # ── Stage 12: Multi-Artifact Final Reporting ─────────────────
        st12 = self._eval_stage_12()
        stages.append(st12)

        total_awarded = sum(s.awarded_score for s in stages)
        grade, verdict = self._determine_grade(total_awarded)

        return BenchmarkReport(
            total_score=round(total_awarded, 1),
            grade=grade,
            verdict=verdict,
            stages=stages,
            elapsed_seconds=round(time.time() - t0, 2)
        )

    def _determine_grade(self, score: float) -> Tuple[str, str]:
        if score >= 90.0:
            return "Grade A+ (Autonomous Cognitive Agent)", "Agent exhibits full autonomy, scientific reasoning, robust self-healing, and multi-modal correlation."
        elif score >= 75.0:
            return "Grade A (Advanced Resilient Agent)", "Agent successfully performs complex reasoning and fallback management."
        elif score >= 60.0:
            return "Grade B (Functional Agent)", "Agent performs standard multi-step tasks with basic reasoning."
        elif score >= 40.0:
            return "Grade C (Advanced Tool Runner)", "Agent behaves predominantly like an orchestrator of CLI tools."
        return "Grade D (Basic LLM Wrapper)", "Agent lacks autonomous reasoning and self-healing."

    # ── Individual Stage Evaluators ──────────────────────────────────

    def _eval_stage_0(self) -> StageResult:
        """Stage 0: Basics & Workspace Organization (10 pts)"""
        wm = WorkspaceManager(root=self.workspace_root)
        target = "lab.local"
        session_id = "bench_00"

        ws_path = wm.create_workspace(target, session_id)
        expected_dirs = ["recon", "web", "browser", "nmap", "ffuf", "evidence", "reports"]
        all_created = all((ws_path / d).exists() for d in expected_dirs)

        state_file = wm.get_state_file(target, session_id)
        state = MissionState.load_or_create(state_file, target=target)
        state.mark_skill_done("test_skill")
        state.save(state_file)
        loaded = MissionState.load(state_file)

        passed = all_created and loaded.is_skill_done("test_skill")
        score = 10.0 if passed else 0.0
        return StageResult(
            stage_number=0,
            stage_name="Basics & Workspace Organization",
            max_score=10.0,
            awarded_score=score,
            passed=passed,
            details=[f"All structured directories verified: {all_created}", "State persistence & loading verified"]
        )

    def _eval_stage_1(self) -> StageResult:
        """Stage 1: Tool Discovery & Dynamic Planning (10 pts)"""
        registry = SkillRegistry()
        count = registry.discover(force=True)
        planner = MissionPlanner(registry)

        state = MissionState.create_new(target="lab.local")
        ready_skills = planner.get_ready_skills(state)

        # Check that planner groups by priority rather than dumping everything
        batches = planner.group_independent_skills(ready_skills, max_batch_size=3)

        manifest_reg = ToolManifestRegistry()
        fuzzers = manifest_reg.find_tools_by_capability("content_discovery")

        passed = count >= 10 and len(ready_skills) >= 2 and len(batches) >= 1 and len(fuzzers) >= 1
        score = 10.0 if passed else 0.0
        return StageResult(
            stage_number=1,
            stage_name="Tool Discovery & Dynamic Planning",
            max_score=10.0,
            awarded_score=score,
            passed=passed,
            details=[f"Discovered {count} modular skills", f"DAG partitioned into {len(batches)} parallel batches", f"Discovered {len(fuzzers)} fuzzing manifests"]
        )

    def _eval_stage_2(self) -> StageResult:
        """Stage 2: File & Artifact Intelligence (10 pts)"""
        wm = WorkspaceManager(root=self.workspace_root)
        target = "lab.local"
        session_id = "bench_02"

        # Write simulated recon and web files
        p1 = wm.write_file(target, "recon", "subdomains.txt", "api.lab.local\napp.lab.local", session_id)
        p2 = wm.write_file(target, "web", "endpoints.txt", "/api/v1/user\n/login", session_id)

        ctx = SkillContext(
            target=target,
            session_id=session_id,
            workspace=wm,
            tool_manager=None,
            state_files={"subdomain_enum": str(p1), "crawling": str(p2)}
        )

        read_sub = ctx.read_skill_output("subdomain_enum", "subdomains.txt")
        read_ep = ctx.read_skill_output("crawling", "endpoints.txt")

        passed = read_sub is not None and "api.lab.local" in read_sub and read_ep is not None and "/login" in read_ep
        score = 10.0 if passed else 0.0
        return StageResult(
            stage_number=2,
            stage_name="File & Artifact Intelligence",
            max_score=10.0,
            awarded_score=score,
            passed=passed,
            details=["Cross-skill artifact data exchange verified", "Structured file persistence verified"]
        )

    def _eval_stage_3(self) -> StageResult:
        """Stage 3: Dependency & Degradation Resilience (10 pts)"""
        registry = SkillRegistry()
        registry.discover(force=True)
        planner = MissionPlanner(registry)

        state = MissionState.create_new(target="lab.local")
        # Simulate primary DNS failure
        state.mark_skill_failed("subdomain_enum", "DNS server unreachable")

        # Planner should not crash; it should recommend alternative fallback
        fallbacks = planner.get_fallback_skills("subdomain_enum", state)
        ready = planner.get_ready_skills(state)

        passed = len(fallbacks) >= 1 and any(f.name == "dns_enum" for f in fallbacks) and len(ready) >= 1
        score = 10.0 if passed else 0.0
        return StageResult(
            stage_number=3,
            stage_name="Dependency & Degradation Resilience",
            max_score=10.0,
            awarded_score=score,
            passed=passed,
            details=[f"Primary failure gracefully caught", f"Fallback skill recommended: {[f.name for f in fallbacks]}"]
        )

    async def _eval_stage_4(self) -> StageResult:
        """Stage 4: Playwright & Browser Intelligence (10 pts)"""
        from core.browser.browser_interface import CognitiveBrowserInterface
        from core.browser.markdown_extractor import MarkdownExtractor

        sample_dom = """
        <html>
            <head><title>Secure Dashboard</title></head>
            <body>
                <a href="/profile">Profile</a>
                <form action="/api/login" method="POST">
                    <input type="text" name="user" required />
                    <input type="password" name="pass" required />
                    <button type="submit">Login</button>
                </form>
            </body>
        </html>
        """
        extracted = MarkdownExtractor.extract_from_html(sample_dom, base_url="https://app.local")
        interface = CognitiveBrowserInterface(headless=True)
        act_res = await interface.act("click", "#login-btn")

        passed = extracted.title == "Secure Dashboard" and len(extracted.links) >= 1 and act_res.success
        score = 10.0 if passed else 0.0
        return StageResult(
            stage_number=4,
            stage_name="Playwright & Browser Intelligence",
            max_score=10.0,
            awarded_score=score,
            passed=passed,
            details=["Clean DOM extraction verified", "Form analysis & action simulation verified"]
        )

    def _eval_stage_5(self) -> StageResult:
        """Stage 5: Dynamic State Observation (5 pts)"""
        from core.browser.browser_interface import PageObservation
        obs1 = PageObservation(url="https://app.local/", title="Homepage", interactable_elements=[{"label": "Login"}])
        obs2 = PageObservation(url="https://app.local/dashboard", title="Dashboard", interactable_elements=[{"label": "Logout"}])

        diff_detected = obs1.url != obs2.url and obs1.title != obs2.title
        passed = diff_detected
        score = 5.0 if passed else 0.0
        return StageResult(
            stage_number=5,
            stage_name="Dynamic State Observation",
            max_score=5.0,
            awarded_score=score,
            passed=passed,
            details=["State transition and DOM diffing verified"]
        )

    def _eval_stage_6(self) -> StageResult:
        """Stage 6: UI <-> Network Traffic Correlation (10 pts)"""
        db_path = self.workspace_root / "test_corr.db"
        db = KnowledgeDB(db_path)
        correlator = UITrafficCorrelator(db, max_time_delta_seconds=2.0)

        t_now = time.time()
        actions = [{"action_id": "act_01", "element_type": "button", "text_label": "Update Profile", "locator": "#btn-upd", "timestamp": t_now}]
        traffic = [{"req_id": "req_01", "method": "PATCH", "url": "https://api.local/profile/99", "status_code": 200, "post_data": '{"name": "test"}', "timestamp": t_now + 0.1}]

        corrs = correlator.correlate_events(actions, traffic)
        passed = len(corrs) >= 1 and corrs[0].confidence >= 0.80 and corrs[0].method == "PATCH"
        score = 10.0 if passed else 0.0
        return StageResult(
            stage_number=6,
            stage_name="UI <-> Network Traffic Correlation",
            max_score=10.0,
            awarded_score=score,
            passed=passed,
            details=[f"Correlated {len(corrs)} UI actions to network requests", f"Confidence: {corrs[0].confidence:.0%}"]
        )

    def _eval_stage_7(self) -> StageResult:
        """Stage 7: Scientific Security Reasoning (10 pts)"""
        db_path = self.workspace_root / "test_reason.db"
        db = KnowledgeDB(db_path)
        engine = HypothesisReasoningEngine(db)

        # Observation: Exposed user ID
        endpoints = [{"url": "https://app.local/api/users?user_id=101", "path": "/api/users"}]
        params = [{"name": "user_id", "sample_value": "101", "is_identifier": True}]
        hyps = engine.generate_hypotheses_from_observations("app.local", endpoints, params, ["AWS"])

        # Validation updates confidence
        conf_after = engine.record_validation_result(hyps[0].hyp_id, corroborating=True, evidence_snippet="Tenant mismatch confirmed", confidence_delta=0.35)

        passed = len(hyps) >= 1 and hyps[0].recommended_skill == "authorization_analysis" and conf_after >= 0.90
        score = 10.0 if passed else 0.0
        return StageResult(
            stage_number=7,
            stage_name="Scientific Security Reasoning",
            max_score=10.0,
            awarded_score=score,
            passed=passed,
            details=[f"Formulated hypothesis: {hyps[0].title}", f"Confidence upgraded to {conf_after:.0%}"]
        )

    def _eval_stage_8(self) -> StageResult:
        """Stage 8: False Positive Filtering & Gating (5 pts)"""
        # Weak finding without reproduction steps
        weak_finding = {"title": "Possible Vulnerability", "evidence": "Saw parameter in URL", "type": "idor"}
        eval_weak = SevenQuestionGate.evaluate_finding(weak_finding)

        # Strong finding with complete proof
        strong_finding = {
            "title": "Confirmed IDOR via Tenant Isolation Bypass",
            "evidence": "Observed HTTP 200 with full PII disclosure when requesting user_id=42 from user_id=41 session",
            "type": "broken_access_control.idor",
            "url": "https://api.local/v1/users/42"
        }
        eval_strong = SevenQuestionGate.evaluate_finding(strong_finding)

        passed = eval_weak.passed is False and eval_strong.passed is True
        score = 5.0 if passed else 0.0
        return StageResult(
            stage_number=8,
            stage_name="False Positive Filtering & Gating",
            max_score=5.0,
            awarded_score=score,
            passed=passed,
            details=["7-Question Gate successfully flags weak findings", "Complete findings pass with high score"]
        )

    def _eval_stage_9(self) -> StageResult:
        """Stage 9: Memory Persistence & Resume (5 pts)"""
        state_path = self.workspace_root / "resume_state.json"
        s1 = MissionState.create_new(target="lab.local")
        s1.mark_skill_done("subdomain_enum")
        s1.mark_skill_done("port_scan")
        s1.save(state_path)

        # Simulate agent restart & resume
        s2 = MissionState.load(state_path)
        passed = s2.is_skill_done("subdomain_enum") and s2.is_skill_done("port_scan")
        score = 5.0 if passed else 0.0
        return StageResult(
            stage_number=9,
            stage_name="Memory Persistence & Resume",
            max_score=5.0,
            awarded_score=score,
            passed=passed,
            details=["State persisted to JSON and resumed without loss"]
        )

    def _eval_stage_10(self) -> StageResult:
        """Stage 10: Tool Failure Recovery & Fallbacks (5 pts)"""
        state = MissionState.create_new(target="lab.local")
        r1 = state.increment_retry("port_scan")
        r2 = state.increment_retry("port_scan")

        passed = r2 == 2 and state.get_retry_count("port_scan") == 2 and len(state.timeline) >= 2
        score = 5.0 if passed else 0.0
        return StageResult(
            stage_number=10,
            stage_name="Tool Failure Recovery & Fallbacks",
            max_score=5.0,
            awarded_score=score,
            passed=passed,
            details=["Retry counter & timeline tracking verified"]
        )

    def _eval_stage_11(self) -> StageResult:
        """Stage 11: Scope Guard & Sandboxing (5 pts)"""
        mgr = CapabilityManager(workspace_root=self.workspace_root)
        token = mgr.create_skill_token("sandboxed_skill", ["filesystem.read", "filesystem.write"])

        inside_ok = mgr.verify_sandbox_path(self.workspace_root / "safe.txt", token)
        outside_blocked = not mgr.verify_sandbox_path(Path("C:/Windows/System32") if self.workspace_root.drive else Path("/etc"), token)

        passed = inside_ok and outside_blocked
        score = 5.0 if passed else 0.0
        return StageResult(
            stage_number=11,
            stage_name="Scope Guard & Sandboxing",
            max_score=5.0,
            awarded_score=score,
            passed=passed,
            details=["Sandbox enclosure protects host system from uncontained access"]
        )

    def _eval_stage_12(self) -> StageResult:
        """Stage 12: Multi-Artifact Final Reporting (5 pts)"""
        wm = WorkspaceManager(root=self.workspace_root)
        em = EvidenceManager()
        reporter = MissionReporter(wm, em)

        state = MissionState.create_new(target="lab.local")
        state.mark_skill_done("subdomain_enum")
        state.add_finding({
            "title": "Exposed API Endpoint",
            "evidence": "Endpoint returned status 200 without token",
            "type": "api_surface",
            "severity": "Medium"
        })

        report_file = reporter.generate_report(state)
        summary_file = report_file.parent / "summary.json"

        passed = report_file.exists() and summary_file.exists() and "CVSS" in report_file.read_text(encoding="utf-8")
        score = 5.0 if passed else 0.0
        return StageResult(
            stage_number=12,
            stage_name="Multi-Artifact Final Reporting",
            max_score=5.0,
            awarded_score=score,
            passed=passed,
            details=["Generated final_report.md with CVSS and summary.json"]
        )
