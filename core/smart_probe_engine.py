# ─── 1. WAF DETECTOR & ADAPTOR ──────────────────────────────────────────────
class WAFDetector:
    """كاشف جدران الحماية (WAF) ومحدد آليات التكيف"""

    SIGNATURES = {
        "Cloudflare": {
            "headers": ["cf-ray", "__cfduid", "cf-cache-status", "cf-mitigated"],
            "server": ["cloudflare"],
            "body": ["cloudflare", "attention required! | cloudflare", "ray id:"]
        },
        "AWS WAF": {
            "headers": ["x-amz-cf-id", "x-amzn-requestid", "awselb"],
            "server": ["awselb", "amazon"],
            "body": ["403 forbidden", "aws waf"]
        },
        "Akamai": {
            "headers": ["x-akamai-transformed", "akamai-origin-hop"],
            "server": ["akamaighost", "akamai"],
            "body": ["access denied", "you don't have permission to access"]
        },
        "ModSecurity": {
            "headers": ["mod_security", "nox-security"],
            "server": ["mod_security", "modsecurity"],
            "body": ["mod_security", "modsecurity", "this error was generated by mod_security"]
        },
        "Imperva Incapsula": {
            "headers": ["x-cdn", "incap_ses", "visid_incap"],
            "server": ["incapsula"],
            "body": ["incapsula incident id", "powered by incapsula"]
        },
        "Sucuri": {
            "headers": ["x-sucuri-id", "x-sucuri-cache"],
            "server": ["sucuri"],
            "body": ["access denied - sucuri website firewall", "sucuri webproxy"]
        }
    }

    @staticmethod
    def detect_waf(headers: Dict[str, str], body: str, status_code: int) -> Dict[str, Any]:
        detected_wafs = []
        h_lower = {k.lower(): v.lower() for k, v in headers.items()}
        b_lower = body.lower()
        server_hdr = h_lower.get("server", "")

        for waf_name, sigs in WAFDetector.SIGNATURES.items():
            matched = False
            for hdr in sigs["headers"]:
                if hdr in h_lower:
                    matched = True
                    break
            if not matched:
                for s in sigs["server"]:
                    if s in server_hdr:
                        matched = True
                        break
            if not matched:
                for phrase in sigs["body"]:
                    if phrase in b_lower and status_code in (403, 406, 429, 503):
                        matched = True
                        break

            if matched:
                detected_wafs.append(waf_name)

        is_present = len(detected_wafs) > 0
        recommended_delay = 2.5 if is_present else 0.5

        return {
            "waf_detected": is_present,
            "wafs": detected_wafs if is_present else ["None (Direct Origin)"],
            "recommended_delay": recommended_delay,
            "recommended_headers": {
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
                "X-Forwarded-For": "127.0.0.1",
                "X-Originating-IP": "127.0.0.1"
            } if is_present else {}
        }


# ─── 2. STEALTH MODE & RATE CONTROLLER ──────────────────────────────────────
class StealthController:
    """متحكم السرعة والتخفي لمنع حظر الـ IP وتجاوز الـ Rate Limits"""

    def __init__(self, base_delay: float = 1.0, jitter_pct: float = 0.3):
        self.base_delay = base_delay
        self.jitter_pct = jitter_pct
        self.last_request_time = 0.0

    async def throttle(self, extra_delay: float = 0.0):
        current_time = time.time()
        elapsed = current_time - self.last_request_time
        jitter = random.uniform(-self.jitter_pct, self.jitter_pct) * self.base_delay
        effective_delay = max(0.1, self.base_delay + jitter + extra_delay)

        if elapsed < effective_delay:
            wait_time = effective_delay - elapsed
            await time.sleep(wait_time) if hasattr(time, "sleep_async") else None
            # Standard asyncio sleep
            import asyncio
            await asyncio.sleep(wait_time)

        self.last_request_time = time.time()


